"""Build transparent full-animation assets from the separate decomp checkout.

Usage: python tools/build-flash-animations.py /path/to/Age-of-War-Flash-Decompiled
Requires Pillow. The decompiled PNGs remain outside this repository.
"""
import argparse
import hashlib
from pathlib import Path
from PIL import Image

# Idle, walk, melee, shoot, shootwalk, death. Character IDs are from the SWF's
# DefineSprite_687 and each character's animation-state timeline.
CLIPS = [
    [230,231,237,230,231,245], [259,260,263,278,280,264],
    [310,311,315,310,311,317], [334,335,348,334,335,349],
    [369,370,380,393,404,381], [448,449,450,448,449,452],
    [468,469,471,468,469,472], [478,479,482,482,484,483],
    [494,495,497,494,495,498], [514,515,516,514,515,517],
    [521,522,532,542,551,533], [568,569,573,568,569,607],
    [630,631,639,630,631,640], [646,647,654,661,662,655],
    [676,676,681,676,676,685], [646,647,654,661,662,655],
]
SCALE = 400 / 650

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('reference', type=Path)
    args = ap.parse_args()
    source = args.reference / 'Games/age of war/The game/sprites'
    repo = Path(__file__).resolve().parents[1]
    output = repo / '3ds/gfx/flash_units'
    output.mkdir(parents=True, exist_ok=True)
    unique, paths, areas, frames, clips, ids = {}, [], [], [], [], {}
    for sid in sorted({sid for row in CLIPS for sid in row}):
        directory = source / f'DefineSprite_{sid}'
        files = sorted(directory.glob('*.png'), key=lambda f: int(f.stem))
        if not files:
            raise FileNotFoundError(directory)
        offset = len(frames)
        for file in files:
            im = Image.open(file).convert('RGBA')
            im = im.resize((max(1,round(im.width*SCALE)),max(1,round(im.height*SCALE))), Image.Resampling.LANCZOS)
            digest = hashlib.sha256(str(im.size).encode()+im.tobytes()).hexdigest()
            if digest not in unique:
                index = len(paths)
                path = output / f'f{index:04d}.png'
                im.save(path)
                unique[digest] = index
                paths.append(f'flash_units/{path.name}')
                areas.append((im.width+2)*(im.height+2))
            frames.append(unique[digest])
        ids[sid] = len(clips)
        clips.append((offset,len(files)))
    header = ['// Generated by tools/build-flash-animations.py.','#pragma once',
              f'#define FLASH_ART_COUNT {len(paths)}',
              'struct FlashClip { int first; int count; };',
              'static const unsigned short FLASH_FRAME_ART[] = {',
              ','.join(map(str,frames)), '};',
              'static const FlashClip FLASH_CLIPS[] = {',
              ','.join('{%d,%d}'%c for c in clips), '};',
              'static const unsigned short FLASH_UNIT_CLIPS[16][6] = {']
    header += ['{'+','.join(str(ids[sid]) for sid in row)+'},' for row in CLIPS]
    header += ['};','']
    (repo/'3ds/source/flash_art.h').write_text('\n'.join(header),encoding='utf-8')
    # PICA200 textures are limited to 1024x1024. Separate pages also avoid a
    # single enormous allocation. ETC1A4 preserves alpha within old-3DS RAM.
    pages, first, area = [], 0, 0
    for i, size in enumerate(areas):
        if area+size > 600000 and i>first:
            pages.append((first,i))
            first, area = i, 0
        area += size
    pages.append((first,len(paths)))
    sheets = ['// Generated by tools/build-flash-animations.py.','#pragma once']
    for page,(start,end) in enumerate(pages):
        name = f'flash_units_{page:02d}'
        (repo/f'3ds/gfx/{name}.t3s').write_text('--atlas -f etc1a4 -q high -z auto\n\n'+'\n'.join(paths[start:end])+'\n',encoding='utf-8')
        sheets.append(f'#include "{name}_t3x.h"')
    sheets += [f'#define FLASH_SHEET_COUNT {len(pages)}',
               'static const void* const FLASH_SHEET_DATA[] = {',
               ','.join(f'flash_units_{i:02d}_t3x' for i in range(len(pages))), '};',
               'static const unsigned int* const FLASH_SHEET_SIZES[] = {',
               ','.join(f'&flash_units_{i:02d}_t3x_size' for i in range(len(pages))), '};',
               'static const int FLASH_SHEET_FIRST[] = {',','.join(str(a) for a,b in pages),'};',
               'static const int FLASH_SHEET_LENGTH[] = {',','.join(str(b-a) for a,b in pages),'};','']
    (repo/'3ds/source/flash_unit_sheets.h').write_text('\n'.join(sheets),encoding='utf-8')
    obsolete = repo/'3ds/gfx/flash_units.t3s'
    if obsolete.exists(): obsolete.unlink()
    # Original forest backdrop; keep its entire scrollable width.
    bg = Image.open(source/'DefineSprite_50_bg/1.png').convert('RGBA')
    bg.resize((round(bg.width*SCALE),round(bg.height*SCALE)),Image.Resampling.LANCZOS).save(repo/'3ds/gfx/background.png')
    print(f'{len(paths)} unique frames, {len(frames)} timeline frames, {len(clips)} clips, {len(pages)} atlas pages; alpha retained')

if __name__ == '__main__':
    main()
